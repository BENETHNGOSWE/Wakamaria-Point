def _interpolate(knots, probability):
    if not knots:
        return probability
    if probability <= knots[0][0]:
        return knots[0][1]
    for (x0, y0), (x1, y1) in zip(knots, knots[1:]):
        if probability <= x1:
            if x1 <= x0:
                return y1
            share = (probability - x0) / (x1 - x0)
            return y0 + (y1 - y0) * share
    return knots[-1][1]


def calibrate(tip, probability):
    """What this stated probability has historically meant in real matches."""
    if probability is None:
        return None
    return _interpolate(CURVES.get(tip), float(probability))


def calibrate_all(probabilities):
    """Calibrate every market in one pass."""
    return {tip: calibrate(tip, p) for tip, p in (probabilities or {}).items()}
