def _interpolate(knots, probability):
    """Map a stated probability onto the observed one.

    Outside the fitted range the curve is extended toward the corners (0, 0)
    and (1, 1) rather than held flat. Holding it flat was a real bug: the table
    tops out where ordinary league matches stop, so a Barcelona-vs-minnow tie
    that is genuinely 88% to see three goals could never be stated above 64%.
    The model then ignored a near-certainty and published the safer-looking
    option beside it.
    """
    if not knots:
        return probability
    p = min(max(probability, 0.0), 1.0)
    if p <= knots[0][0]:
        x0, y0 = knots[0]
        return y0 * (p / x0) if x0 > 0 else 0.0
    if p >= knots[-1][0]:
        x1, y1 = knots[-1]
        if x1 >= 1.0:
            return y1
        return y1 + (p - x1) / (1.0 - x1) * (1.0 - y1)
    for (x0, y0), (x1, y1) in zip(knots, knots[1:]):
        if p <= x1:
            if x1 <= x0:
                return y1
            share = (p - x0) / (x1 - x0)
            return y0 + (y1 - y0) * share
    return knots[-1][1]


def calibrate(tip, probability):
    """What this stated probability has historically meant in real matches."""
    if probability is None:
        return None
    return _interpolate(CURVES.get(tip), float(probability))


def calibrate_all(probabilities):
    """Calibrate every market in one pass."""
    return {tip: calibrate(tip, p) for tip, p in (probabilities or {}).items()}
